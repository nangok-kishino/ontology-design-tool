// 知見の切り分け基準：文書の中の知見を、グラフにするか、文章のままベクトル RAG で扱うか。
//
// 画面「知見の切り分け基準」と、LLM による解析への指示の両方がこれを読む。
// 人が確認している基準と、LLM が従っている基準を同じものにするため、内容はここにだけ書く。

export type KnowledgeScopeRow = {
  kind: string
  // どちらで扱うか
  handling: "グラフ" | "グラフ（骨組み）" | "ベクトルRAG"
  reason: string
  example: string
}

export const KNOWLEDGE_SCOPE: KnowledgeScopeRow[] = [
  {
    kind: "制約・禁忌（ルール）",
    handling: "グラフ",
    reason: "対象（材料、部品、仕向け地）と、それに対する可否がはっきり特定でき、該当するかしないかで判断が決まる。解釈の余地がない。",
    example: "「材料Aと接着剤Bは組み合わせてはならない」「仕向け地EUでは部品Xは使えない」",
  },
  {
    kind: "因果関係（過去トラブル・設変）",
    handling: "グラフ（骨組み）",
    reason: "個々の事象（部品、現象、原因、対策）がそれぞれ特定でき、原因と結果のつながりが複数の事象・文書をまたいで続く。",
    example: "「部品A」→[発生]→「現象：異音」→[原因]→「クリアランス不足」→[対策]→「部品Bへ設変」",
  },
  {
    kind: "トラブルの詳細レポート・経緯",
    handling: "ベクトルRAG",
    reason: "価値が、試験条件、経過、判断に至った筋道といった文脈の連なりにある。要素に切り分けると、なぜその結論に至ったかが失われる。",
    example: "「どんな試験条件で、どのような振動波形が出て、なぜその結論に至ったか」",
  },
  {
    kind: "作業のコツ・定性的なノウハウ",
    handling: "ベクトルRAG",
    reason: "条件と効果が「少し」「出にくい」のように程度で語られ、対象や条件の境目がはっきりしない。言い回しそのものに意味がある。",
    example: "「この公差を狙うときは、治具を少し斜めに当てるとバリが出にくい」",
  },
]

// LLM に渡す指示文。基準の表をそのまま並べ、判断のしかたを添える。
export function knowledgeScopePrompt(): string {
  const rows = KNOWLEDGE_SCOPE.map((r) =>
    `- ${r.kind}｜${r.handling === "ベクトルRAG" ? "グラフにしない（文章のままベクトルRAGで扱う）" : r.handling === "グラフ" ? "グラフにする" : "グラフにする（骨組みだけ）"}\n` +
    `  理由：${r.reason}\n  例：${r.example}`,
  ).join("\n")
  return [
    "【知見の切り分け基準】（必ず従ってください）",
    "文書の中の知見を、グラフにするか、文章のままベクトルRAG（別の仕組み）で扱うかを、次の基準で切り分けます。",
    rows,
    "判断のしかた：",
    "- グラフにするのは、対象がそれぞれ特定でき、関係や可否がはっきり言い切れるものだけです。",
    "- 価値が文脈の連なり（条件・経過・判断の筋道）にあるもの、程度で語られ境目がはっきりしないものは、グラフにしません。候補に挙げないでください。",
    "- 因果関係は、事象（部品・現象・原因・対策）と、そのつながりという骨組みだけを取り出します。経緯や考察の文章はノード名・ラベル・タイプにしません。",
    "- 判断の理由や説明の文章そのものを、ノード名・ラベル・タイプにしないでください。",
  ].join("\n")
}
